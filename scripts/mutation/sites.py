#!/usr/bin/env python3
"""Finds the sites of the mutation runner in MoonBit source, and prints one
site per line, as JSON. A site is one change that one operator can make at
one place (CONTRIBUTING.md, "Mutation runner").

usage: python3 scripts/mutation/sites.py [--root <dir>] [--target <backend>]
           [--set pinned|full] <path>...

Each <path> is a package's directory, whose .mbt files are read, or one
.mbt file, relative to <root> (the current directory unless it is given).
Test files (*_test.mbt, *_wbtest.mbt), test blocks, and generated files
have no sites. A generated file is one whose first line is
"// Generated by <what>. Do not edit.": the Unicode data table, the build
information and the test certificates are.

The operators are those of operator set v1, which operators.py defines:
which alternatives each makes at a position, which of them the pinned set
takes, and which sites a rule skips. This script finds the positions:

  BODY  a top-level function's or method's body
  ROR   a comparison (<, <=, > and >=)
  IFC   the condition of an if or an else if, of a while or a for loop,
        a match arm's guard, and a guard statement's condition
  LCR   && and ||
  NOT   a prefix !
  DEL   a statement that is a call or an assignment (compound ones and
        those to a field or an element included): one whose value its
        block drops, or the last one of a block whose value is Unit (a
        function's body that returns Unit, a loop's body, an if's body
        without an else), but not the only one of a function's body,
        whose BODY site makes the same mutant
  BOOL  true and false
  AOR   +, -, * and /, and their compound assignments
  INT   an integer literal; it is in a comparison or an index when it is
        an operand of a comparison (<, <=, >, >=, == or !=) or the index
        of an element or a slice, directly or through +, -, *, / and %
  STR   a string or byte-string literal, interpolated or over several
        lines too (not a character literal)

Literals in patterns are not sites, nor are ranges (..< and ..=), == and
!= for ROR, and not(...) calls. Where two sites make the same mutant (the
same text, but for white space at the edges of the change), only one is
kept: the pinned one, then the one whose operator comes first in
operators.DEDUPLICATION.

--set pinned, the default, prints the sites of the pinned set, one
mutant per position (two for INT in a comparison or an index); --set full
prints every alternative of every operator at every position, each with
whether the pinned set takes it.

Each line is a JSON object. A site has:

  id                the mutant's id: the six fields below, joined by ","
                    (a "\\" escapes a "," or a "\\" in a field, and "\\n",
                    "\\r" and "\\t" stand for those characters); in the
                    id, an original or a replacement over several lines is
                    written as its first line, "…" and its last line,
                    without the indentation
  file              the file, relative to <root>, with "/"
  definition        the top-level definition that holds the site: "f",
                    "Type::f", "impl Trait for Type with f", a let or a
                    const's name, a type's or a trait's name, main or init
  operator          one of operator set v1's
  original          the text the site replaces
  replacement       the text that replaces it ("" for NOT and DEL)
  ordinal           how many sites with the same file, definition,
                    operator, original and replacement, as the id writes
                    them, come before it in the file, from 0
  line, column      where the original text starts, from 1; a column counts
                    characters (Unicode code points)
  definition_lines  the first and the last line of the definition
  pinned            whether the pinned set takes it
  operator_set      the version of the operator set, "v1"

A site that a rule skips is printed as well, so that a report can count
it: it has the same fields but id and ordinal, and "skipped", the rule's
reason (operators.SKIPS): "no default" and "FFI" (BODY), "outside scope"
(STR), "binds a name" (IFC and LCR) or "string operand" (AOR).

The lines are sorted by file, then by position. The ids stay the same as
long as a definition's sites of the same kind keep their order.

The parser is the pinned compiler's own: `moonc compile -dsource -show-loc`
writes the parse tree of a file, with the position of every node, beside
it. The file is copied into a temporary directory first, so the tree is
written there. The compiler then fails to type the file, which it reads
without its package; only a parse error fails this script. Every site's
original text is checked against the source at the position the tree
gives, so a tree that changes shape fails the script instead of giving a
wrong site. --target is the backend whose conditional compilation the
compiler applies (wasm-gc unless it is given). The runner,
scripts/mutation/run.py, reads only these lines, so another parser can
replace this one without a change to the runner.
"""

