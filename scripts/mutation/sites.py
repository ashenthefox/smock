import operators as ops

GENERATED = re.compile(r"^// Generated by .+\. Do not edit\.$")
LOC = re.compile(r"^(\d+):(\d+)-(\d+):(\d+)$")
# The beginnings of a literal's text, whose value the tree prints as a bare
# word: the string "true", and the bytes b"true", are printed as true.
LITERAL_STARTS = ('"', "'", 'b"', "b'", "#|", "$|")
COMPARISONS = {"<", "<=", ">", ">=", "==", "!="}
# The operators through which an integer literal is still an operand of the
# comparison or the index that holds it.
ARITHMETIC = {"+", "-", "*", "/", "%"}
# The methods that the syntax of an element or a slice calls.
INDEX_METHODS = {"op_get", "op_set", "op_as_view"}
# The statements DEL deletes: calls and assignments.
DELETABLE = {"Pexpr_apply", "Pexpr_dot_apply", "Pexpr_pipe", "Pexpr_assign", "Pexpr_mutate"}
# What a string escape stands for, after its backslash.
ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "b": "\b", "\\": "\\", '"': '"', "'": "'"}


class FinderError(Exception):
    """What stops the finder: a file that does not parse, or a tree it
    cannot read."""


class Change(NamedTuple):
    """One alternative at one position of a definition. A BODY site
    compares its mutant with others by its body's expression, without the
    braces and the comments around it: same_as is that span, and its
    replacement the default value."""

    operator: str
    start: tuple
    end: tuple
    alternative: ops.Alternative
    same_as: tuple | None = None


def is_test_file(path):
    """Whether moon reads the file as tests only."""
    return path.name.endswith(("_test.mbt", "_wbtest.mbt"))


def is_generated(text):
    """Whether the file's first line says that a generator wrote it."""
    return GENERATED.match(text.split("\n", 1)[0]) is not None


def source_files(root, paths):
    """The .mbt files that the paths name, relative to root, without test
    files, sorted."""
    files = set()
    for given in paths:
        path = (root / given).resolve()
        if path.is_dir():
            candidates = sorted(path.glob("*.mbt"))
        elif path.is_file():
            candidates = [path]
        else:
            raise FinderError(f"{given} is neither a package's directory nor a file")
        for file in candidates:
            if file.suffix == ".mbt" and not is_test_file(file):
                files.add(file.relative_to(root.resolve()))
    return sorted(files, key=lambda p: p.as_posix())


def parse_tree(text):
    """The compiler's dump, an S-expression, as nested lists of strings."""
    stack = [[]]
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c in " \t\r\n":
            i += 1
        elif c == "(":
            stack.append([])
            i += 1
        elif c == ")":
            if len(stack) == 1:
                raise FinderError("the parse tree has an unmatched )")
            node = stack.pop()
            stack[-1].append(node)
            i += 1
        elif c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            if j >= n:
                raise FinderError("the parse tree has an unterminated string")
            stack[-1].append(text[i : j + 1])
            i = j + 1
        else:
            j = i
            while j < n and text[j] not in ' \t\r\n()"':
                j += 1
            stack[-1].append(text[i:j])
            i = j
    if len(stack) != 1 or len(stack[0]) != 1 or not isinstance(stack[0][0], list):
        raise FinderError("the parse tree is not one list")
    return stack[0][0]


def child(node, head):
    """The first list among node's elements that starts with head, or None."""
    for element in node:
        if isinstance(element, list) and element and element[0] == head:
            return element
    return None


def head_of(node):
    """The name a node of the tree starts with, or None."""
    return node[0] if isinstance(node, list) and node and isinstance(node[0], str) else None


def walk(node):
    """Every list in node, node included, depth first, without recursion."""
    todo = [node]
    while todo:
        current = todo.pop()
        yield current
        todo.extend(reversed([e for e in current if isinstance(e, list)]))


def first_binder(node):
    """The first name that node binds, or None."""
    for current in walk(node):
        if len(current) == 2 and current[0] == "binder_name" and isinstance(current[1], str):
            return current[1]
    return None


def binds(node):
    """Whether an `is` in node binds a name, which forcing the expression
    that holds it would leave unbound."""
    for current in walk(node):
        if head_of(current) == "Pexpr_is" and len(current) >= 3 and first_binder([current[2]]):
            return True
    return False


def operator_name(info):
    """The operator's name and its location atom, from an infix's or a
    unary's first element."""
    if not isinstance(info, list):
        return None, None
    name, span = child(info, "var_name"), child(info, "loc_")
    if not name or not span:
        return None, None
    return name[1], span[1]


def augmented(node):
    """The operator of a compound assignment, from the list the tree gives
    an assignment, as its name and its location atom; None, None for a
    plain one."""
    for element in node[2:]:
        if (isinstance(element, list) and len(element) == 1 and isinstance(element[0], list)
                and child(element[0], "var_name")):
            return operator_name(element[0])
    return None, None


def is_array_update(node):
    """Whether node is the compound assignment to an element, which the tree
    writes as two lets of names that start with *."""
    if head_of(node) != "Pexpr_let" or len(node) < 4:
        return False
    name = first_binder([node[1]])
    return name is not None and name.startswith("*array")


def deletable(node):
    """Whether DEL may delete the expression, a statement."""
    return head_of(node) in DELETABLE or is_array_update(node)


def tail(node):
    """The expression whose value is a block's: past the block's statements
    and lets."""
    while True:
        head = head_of(node)
        if head == "Pexpr_sequence" and len(node) >= 3:
            node = node[2]
        elif head == "Pexpr_let" and len(node) >= 5 and not is_array_update(node):
            node = node[3]
        elif head == "Pexpr_letmut" and len(node) >= 6:
            node = node[4]
        elif head == "Pexpr_letfn" and len(node) >= 5:
            node = node[3]
        elif head == "Pexpr_guard" and len(node) >= 4:
            node = node[3]
        else:
            return node


class SourceFile:
    """A file's text, and where each of its lines starts."""

    def __init__(self, path, text):
        self.path = path
        self.text = text
        self.starts = [0]
        for line in text.split("\n"):
            self.starts.append(self.starts[-1] + len(line) + 1)

    def offset(self, line, column):
        """The offset of a line and a column, both from 1."""
        if not 1 <= line < len(self.starts):
            raise FinderError(f"{self.path}: the parse tree names line {line}, which the file does not have")
        return self.starts[line - 1] + column - 1

    def position(self, offset):
        """The line and the column, both from 1, of an offset."""
        line = bisect.bisect_right(self.starts, offset)
        return line, offset - self.starts[line - 1] + 1

    def between(self, start, end):
        """The text from one (line, column) to another, the end excluded."""
        return self.text[self.offset(*start) : self.offset(*end)]


def escape_at(text, index):
    """The length of the string escape at text[index], a backslash, and the
    character it stands for."""
    following = text[index + 1 : index + 2]
    if following in ESCAPES:
        return 2, ESCAPES[following]
    if following == "x":
        return 4, chr(int(text[index + 2 : index + 4], 16))
    if following == "o":
        return 5, chr(int(text[index + 2 : index + 5], 8))
    if following == "u" and text[index + 2 : index + 3] == "{":
        close = text.index("}", index)
        return close + 1 - index, chr(int(text[index + 3 : close], 16))
    if following == "u":
        return 6, chr(int(text[index + 2 : index + 6], 16))
    return 2, following


class Item:
    """One top-level definition of the parse tree, with its base line: the
    tree gives each position inside it as a line relative to that base."""

    def __init__(self, source, base, node):
        self.source = source
        self.node = node
        match = re.match(r"^(\d+):(\d+)$", base)
        if not match or match.group(2) != "1":
            raise FinderError(f"{source.path}: unexpected base position {base} in the parse tree")
        self.base = int(match.group(1))

    def loc(self, atom):
        """A location atom as ((line, column), (line, column)) in the file,
        or None when it is not one or the compiler made it up (0:0-0:0)."""
        if not isinstance(atom, str):
            return None
        match = LOC.match(atom)
        if not match:
            return None
        l1, c1, l2, c2 = (int(g) for g in match.groups())
        if (l1, c1, l2, c2) == (0, 0, 0, 0):
            return None
        return (self.base + l1, c1), (self.base + l2, c2)

    def span_of(self, node):
        """The location of an expression, its last element."""
        span = self.loc(node[-1]) if isinstance(node, list) and node else None
        if span is None:
            raise FinderError(f"{self.source.path}: a {head_of(node)} node of the parse tree has no position")
        return span

    def text_of(self, node):
        """The source text of a node that ends with, or holds, its location."""
        for element in [node[-1]] + [e[1] for e in node if isinstance(e, list) and len(e) == 2 and e[0] == "loc_"]:
            span = self.loc(element)
            if span:
                return self.source.between(*span)
        return None

    def is_test(self):
        """Whether the definition is a test block."""
        kind = self.node[0]
        if kind == "Ptop_test":
            return True
        if kind == "Ptop_funcdef" and isinstance(self.node[1], list):
            flag = child(self.node[1], "is_test_")
            return flag is not None and flag[1:] == ["true"]
        return False

    def name(self):
        """The definition's name, as the ids give it."""
        node, kind = self.node, self.node[0]
        if kind == "Ptop_funcdef":
            header = node[1]
            name = child(header, "name")
            method = first_binder(name) if name else None
            owner = child(header, "type_name")
            if owner and owner[1:] and isinstance(owner[1], list) and owner[1]:
                type_name = child(owner[1][0], "name")
                if type_name and method:
                    return f"{type_name[1]}::{method}"
            if method:
                return method
        elif kind == "Ptop_impl":
            # The type is optional, so it comes in a list: empty for a
            # trait's default implementation.
            self_type, trait, method = node[1], node[2], node[3]
            trait_text = self.text_of(trait)
            method_name = first_binder([method])
            type_text = self.text_of(self_type[0]) if self_type else None
            if trait_text and method_name and (type_text or not self_type):
                if type_text:
                    return f"impl {trait_text} for {type_text} with {method_name}"
                return f"impl {trait_text} with {method_name}"
        elif kind == "Ptop_expr":
            return "main" if "true" in node[2:-1] else "init"
        elif kind in ("Ptop_letdef", "Ptop_trait"):
            binder = first_binder(node)
            if binder:
                return binder
        elif kind == "Ptop_typedef":
            tycon = child(node[1], "tycon")
            if tycon:
                return tycon[1]
        binder = first_binder(node)
        return f"{kind} {binder}" if binder else kind

    def own_span(self):
        """The location of the whole definition: the last location among its
        own elements (a doc comment can follow it)."""
        for element in reversed(self.node):
            span = self.loc(element)
            if span:
                return span
        return None

    def lines(self):
        """The first and the last line of the definition."""
        span = self.own_span()
        if span:
            return [span[0][0], span[1][0]]
        found = [self.loc(a) for n in walk(self.node) for a in n if isinstance(a, str)]
        found = [s for s in found if s]
        return [min(s[0][0] for s in found), max(s[1][0] for s in found)]

    def function(self):
        """A function's or a method's parts: its body (a Decl_body or a
        Decl_stubs node), its return type (a type node, or None when the
        source writes none), and the elements before the body; None for
        any other definition."""
        node, kind = self.node, self.node[0]
        if kind == "Ptop_funcdef" and len(node) == 4 and head_of(node[2]) in ("Decl_body", "Decl_stubs"):
            returned = child(node[1], "return_type")
            written = returned[1] if returned and len(returned) > 1 and returned[1] else None
            return node[2], (written[0] if written else None), [node[1]]
        if kind == "Ptop_impl":
            for index, element in enumerate(node):
                if head_of(element) == "Decl_body":
                    written = node[index - 2] if index >= 2 else None
                    returned = written[0] if isinstance(written, list) and written and head_of(written[0]) else None
                    if returned is None:
                        trait = child(node[2], "name")
                        method = first_binder([node[3]])
                        trait_name = trait[1].rsplit(".", 1)[-1] if trait else None
                        known = ops.TRAIT_METHODS.get((trait_name, method))
                        returned = ["Ptype_name", [["lid", known]], []] if known else None
                    return element, returned, node[1:index]
        return None

    def type_default(self, node):
        """The default value of a type node, or None."""
        head = head_of(node)
        if head == "Ptype_name":
            lid = child(node[1], "lid") if isinstance(node[1], list) else None
            name = lid[1] if lid and isinstance(lid[1], str) else None
            arguments = [self.type_default(a) for a in node[2]] if len(node) > 2 and isinstance(node[2], list) else []
            return ops.default_value("name", name, arguments)
        if head == "Ptype_option":
            return ops.default_value("option", None, [])
        if head == "Ptype_tuple":
            return ops.default_value("tuple", None, [self.type_default(e) for e in node[1]])
        return None

    def body_sites(self):
        """The BODY site of a function or a method, and its body's root
        expression when the body returns Unit."""
        parts = self.function()
        if parts is None:
            return [], None
        body, returned, header = parts
        span = self.own_span()
        if span is None:
            raise FinderError(f"{self.source.path}: the definition {self.name()} has no position")
        if head_of(body) == "Decl_stubs":
            return [Change("BODY", span[0], span[1], a) for a in ops.foreign()], None
        ends = [self.loc(a)[1] for n in walk(header) for a in n if self.loc(a)]
        text = self.source.text
        brace = self.source.offset(*max(ends))
        while brace < len(text) and text[brace] in " \t\r\n":
            brace += 1
        end = self.source.offset(*span[1])
        if text[brace : brace + 1] != "{" or text[end - 1 : end] != "}":
            raise FinderError(f"{self.source.path}:{span[0][0]}: cannot find the body of {self.name()}")
        start = self.source.position(brace)
        root = body[1]
        default = self.type_default(returned) if returned is not None else None
        root_span = self.loc(root[-1]) if isinstance(root, list) and root else None
        changes = [Change("BODY", start, span[1], a,
                          (root_span[0], root_span[1], default) if root_span and default else None)
                   for a in ops.body(default, text[brace:end], head_of(root) == "Pexpr_unit")]
        return changes, (root if default == "()" else None)

    def sites(self):
        """Every site in the definition, as Changes, skipped ones included."""
        changes, unit_body = self.body_sites()
        yield from changes
        if unit_body is not None:
            last = tail(unit_body)
            if last is not unit_body and deletable(last):
                yield from self.change("DEL", self.span_of(last), ops.statement())
        # Each node with whether it is an operand of a comparison or an
        # index, without recursion: a long function nests deep. A node marks
        # the nodes below it that are such an operand.
        todo = [(self.node, False)]
        marked = set()
        while todo:
            node, operand = todo.pop()
            operand = operand or id(node) in marked
            yield from self.node_sites(node, operand, marked)
            inherits = self.inherits(node)
            for element in node:
                if isinstance(element, list):
                    todo.append((element, operand and inherits))

    def is_string(self, node):
        """Whether an expression is a string or a byte-string literal, or a +
        whose operand is one."""
        head = head_of(node)
        if head in ("Pexpr_interp", "Pexpr_multiline_string"):
            return True
        if head == "Pexpr_constant":
            span = self.loc(node[-1])
            return span is not None and self.source.between(*span).startswith(('"', 'b"'))
        if head == "Pexpr_infix":
            name, _ = operator_name(node[1])
            return name == "+" and (self.is_string(node[2]) or self.is_string(node[3]))
        return False

    def inherits(self, node):
        """Whether an expression's operands are in a comparison or an index
        when it is: an arithmetic operator, a unary minus or a type
        constraint."""
        head = head_of(node)
        if head in ("Pexpr_infix", "Pexpr_unary"):
            name, _ = operator_name(node[1])
            return name in ARITHMETIC
        return head == "Pexpr_constraint"

    def node_sites(self, node, operand, marked):
        """The sites at one node of the tree. Adds to marked the nodes below
        it that are an operand of a comparison or an index."""
        head = head_of(node)
        if head == "Pexpr_infix" and len(node) >= 5:
            name, atom = operator_name(node[1])
            if name in COMPARISONS:
                marked.update((id(node[2]), id(node[3])))
                yield from self.operator_sites("ROR", name, atom, ops.ror(name))
            elif name in ops.LCR:
                yield from self.operator_sites("LCR", name, atom, ops.lcr(name, binds(node[2]) or binds(node[3])))
            elif name in ARITHMETIC:
                text = self.source.between(*self.checked_loc(atom))
                if text not in (name, name + "="):
                    raise FinderError(f"{self.source.path}: the parse tree puts {name!r} where the source has {text!r}")
                string = self.is_string(node[2]) or self.is_string(node[3])
                yield from self.operator_sites("AOR", text, atom, ops.aor(text, string))
        elif head == "Pexpr_unary" and len(node) >= 3:
            name, atom = operator_name(node[1])
            if name == "!":
                yield from self.operator_sites("NOT", "!", atom, ops.not_operator(), length=1)
        elif head == "Pexpr_constant" and len(node) >= 3:
            span = self.loc(node[-1])
            if span is None:
                return
            text = self.source.between(*span)
            if not text.startswith(LITERAL_STARTS) and node[1] in ops.BOOL:
                yield from self.change("BOOL", span, ops.bool_literal(text))
            elif ops.integer_value(text) is not None:
                yield from self.change("INT", span, ops.integer_literal(text, operand))
            elif text.startswith(('"', 'b"')):
                yield from self.string_sites(span, text)
        elif head == "Map_expr_elem" and len(node) >= 5:
            # A map literal's key, a literal with a location of its own.
            span = self.loc(node[3])
            text = self.source.between(*span) if span else ""
            if ops.integer_value(text) is not None:
                yield from self.change("INT", span, ops.integer_literal(text, False))
            elif text.startswith(('"', 'b"')):
                yield from self.string_sites(span, text)
        elif head in ("Pexpr_interp", "Pexpr_multiline_string"):
            span = self.span_of(node)
            yield from self.string_sites(span, self.source.between(*span), node)
        elif head in ("Pexpr_assign", "Pexpr_mutate"):
            name, atom = augmented(node)
            if name is not None:
                text = self.source.between(*self.checked_loc(atom))
                value = node[2] if head == "Pexpr_assign" else node[3]
                yield from self.operator_sites("AOR", text, atom, ops.aor(text, self.is_string(value)))
        elif head == "Pexpr_if" and len(node) >= 5:
            yield from self.condition_sites("if", node[1])
            if node[3] == []:
                yield from self.unit_block(node[2])
        elif head == "Pexpr_guard" and len(node) >= 4:
            yield from self.condition_sites("guard", node[1])
        elif head == "Pexpr_while" and len(node) >= 4:
            yield from self.condition_sites("loop", node[1])
            yield from self.unit_block(node[2])
        elif head == "Pexpr_for" and len(node) >= 6:
            if isinstance(node[2], list) and node[2]:
                yield from self.condition_sites("loop", node[2][0])
            yield from self.unit_block(node[4])
        elif head == "Pexpr_foreach" and len(node) >= 5:
            yield from self.unit_block(node[3])
        elif head == "guard" and len(node) == 2 and isinstance(node[1], list) and len(node[1]) == 1:
            yield from self.condition_sites("match guard", node[1][0])
        elif head == "Pexpr_sequence" and len(node) >= 3 and isinstance(node[1], list):
            for statement in node[1]:
                if deletable(statement):
                    yield from self.change("DEL", self.span_of(statement), ops.statement())
        elif head == "Pexpr_dot_apply" and len(node) >= 5:
            label = child(node[2], "label_name") if isinstance(node[2], list) else None
            label_span = self.loc(child(node[2], "loc_")[1]) if label and child(node[2], "loc_") else None
            if (label and label[1] in INDEX_METHODS and label_span
                    and self.source.between(*label_span).startswith("[") and node[3]):
                marked.add(id(node[3][0]))
        elif head == "Pexpr_array_get_slice" and len(node) >= 4:
            for bound in (node[2], node[3]):
                if isinstance(bound, list) and bound:
                    marked.add(id(bound[0]))
        elif head == "Pexpr_let" and len(node) >= 5:
            name = first_binder([node[1]])
            if name is not None and name.startswith("*index"):
                marked.add(id(node[2]))

    def unit_block(self, block):
        """The DEL site of the last statement of a block whose value is
        Unit, when it is one DEL deletes."""
        last = tail(block)
        if deletable(last):
            yield from self.change("DEL", self.span_of(last), ops.statement())

    def condition_sites(self, kind, condition):
        """The IFC sites of a condition."""
        span = self.span_of(condition)
        text = self.source.between(*span)
        yield from self.change("IFC", span, ops.condition(kind, text, binds(condition)))

    def string_sites(self, span, text, node=None):
        """The STR sites of a string literal: a constant, an interpolated
        one (node is the Pexpr_interp) or one over several lines (node is
        the Pexpr_multiline_string)."""
        literal_start = self.source.offset(*span[0])
        head = head_of(node)
        if head == "Pexpr_multiline_string":
            first, empty = self.multiline_first(node, text, literal_start), '""'
        else:
            content = 2 if text.startswith('b"') else 1
            empty = text[:content] + '"'
            first = None
            if head == "Pexpr_interp":
                for part in node[1]:
                    if head_of(part) == "Interp_lit":
                        part_span = self.loc(part[-1])
                        if part_span and part_span[0] != part_span[1]:
                            first = self.character_at(text, self.source.offset(*part_span[0]) - literal_start)
                            break
            elif content < len(text) - 1:
                first = self.character_at(text, content)
            if first is None:
                first = (content, content, None)
        path = self.source.path.as_posix()
        yield from self.change("STR", span, ops.string_literal(path, text, first, empty))

    def character_at(self, text, index):
        """The first character that text writes at index, as (start, end,
        character)."""
        if text[index] == "\\":
            length, character = escape_at(text, index)
            return index, index + length, character
        return index, index + 1, text[index]

    def multiline_first(self, node, text, literal_start):
        """Where a string over several lines writes its first character, as
        (start, end, character) within text; where its first line's text
        starts, with no character, when it writes none."""
        lines = [m for m in re.finditer(r"([#$])\|([^\n]*)", text)]
        parts = node[1] if isinstance(node[1], list) else []
        if len(lines) != len(parts):
            raise FinderError(f"{self.source.path}: a string over several lines does not match its parse tree")
        for match, part in zip(lines, parts):
            if head_of(part) == "Multiline_interp":
                for piece in part[1]:
                    if head_of(piece) == "Interp_lit":
                        piece_span = self.loc(piece[-1])
                        if piece_span and piece_span[0] != piece_span[1]:
                            return self.character_at(text, self.source.offset(*piece_span[0]) - literal_start)
            elif match.group(2):
                return match.start(2), match.start(2) + 1, text[match.start(2)]
        start = lines[0].start(2)
        return start, start, None

    def operator_sites(self, operator, text, atom, alternatives, length=None):
        """The sites of an operator whose text the tree gives with its
        location, once that text is found there. A length takes that many
        characters from the location's start: a unary's location spans its
        operand too."""
        span = self.checked_loc(atom)
        if length is not None:
            span = (span[0], (span[0][0], span[0][1] + length))
        found = self.source.between(*span)
        if found != text:
            raise FinderError(
                f"{self.source.path}:{span[0][0]}:{span[0][1]}: the parse tree puts {text!r} here,"
                f" but the source has {found!r}"
            )
        for alternative in alternatives:
            yield Change(operator, span[0], span[1], alternative)

    def checked_loc(self, atom):
        """A location atom that must be one."""
        span = self.loc(atom)
        if span is None:
            raise FinderError(f"{self.source.path}: an operator of the parse tree has no position")
        return span

    def change(self, operator, span, alternatives):
        """The changes of one position."""
        for alternative in alternatives:
            yield Change(operator, span[0], span[1], alternative)


def dump(moonc, target, workdir, index, path, text):
    """The parse tree of one file, which moonc writes beside a copy of it."""
    directory = workdir / str(index)
    directory.mkdir()
    copy = directory / path.name
    copy.write_text(text, encoding="utf-8")
    result = subprocess.run(
        [moonc, "compile", "-dsource", "-show-loc", "-target", target, "-error-format", "json",
         copy.name, "-o", "out.wasm"],
        cwd=directory, capture_output=True, text=True,
    )
    for line in (result.stdout + result.stderr).splitlines():
        try:
            diagnostic = json.loads(line)
        except ValueError:
            continue
        code = str(diagnostic.get("error_code", ""))
        if diagnostic.get("level") == "error" and code.startswith("3") and len(code) == 4:
            raise FinderError(f"{path}: moonc cannot parse it: {diagnostic.get('message')}")
    tree = directory / (copy.name + ".ast")
    if not tree.is_file():
        raise FinderError(f"{path}: moonc wrote no parse tree:\n{result.stdout}{result.stderr}")
    return tree.read_text(encoding="utf-8")


def escape(field):
    """A field of an id, with what would split it escaped."""
    return (field.replace("\\", "\\\\").replace(",", "\\,").replace("\n", "\\n")
            .replace("\r", "\\r").replace("\t", "\\t"))


def shorten(text):
    """A text as an id writes it: over several lines, its first line, "…"
    and its last line, without the indentation."""
    lines = text.split("\n")
    if len(lines) == 1:
        return text
    return lines[0].rstrip() + "…" + lines[-1].strip()


def effect(source, start, end, replacement):
    """What a change does to the file: the smallest span it changes, and the
    text there, without what the original and the replacement share at
    either edge, white space included. Two changes with the same effect
    make the same mutant."""
    a, b, new = start, end, replacement
    while True:
        before = (a, b, new)
        original = source.text[a:b]
        prefix = 0
        while prefix < min(len(original), len(new)) and original[prefix] == new[prefix]:
            prefix += 1
        suffix = 0
        while suffix < min(len(original), len(new)) - prefix and original[-1 - suffix] == new[-1 - suffix]:
            suffix += 1
        a, b, new = a + prefix, b - suffix, new[prefix : len(new) - suffix]
        while a < b and source.text[a].isspace():
            a += 1
        while b > a and source.text[b - 1].isspace():
            b -= 1
        new = new.strip()
        if (a, b, new) == before:
            return a, b, new


def file_sites(source, tree_text):
    """The sites of one file, sorted by position, with their ordinals, and
    the sites that a rule skipped."""
    found = []
    for entry in parse_tree(tree_text):
        if not (isinstance(entry, list) and len(entry) == 3 and entry[0] == "base_pos"):
            raise FinderError(f"{source.path}: unexpected entry in the parse tree: {str(entry)[:80]}")
        item = Item(source, entry[1], entry[2])
        if item.is_test():
            continue
        name, lines = item.name(), item.lines()
        found += [(name, lines, change) for change in item.sites()]
    # One entry per position and alternative: the tree can hold a node
    # twice, as it does in a compound assignment to an element.
    unique = {}
    for name, lines, change in found:
        unique.setdefault((change.start, change.end, change.operator, change.alternative.replacement),
                          (name, lines, change))
    entries = list(unique.values())
    keep = deduplicated(source, [change for _, _, change in entries])
    order = {o: i for i, o in enumerate(ops.OPERATORS)}
    counts = {}
    sites = []
    file = source.path.as_posix()
    for index in sorted(keep, key=lambda i: (entries[i][2].start, order[entries[i][2].operator], i)):
        name, lines, change = entries[index]
        original = source.between(change.start, change.end)
        alternative = change.alternative
        site = {"file": file, "definition": name, "operator": change.operator,
                "original": original, "replacement": alternative.replacement}
        if alternative.skipped is None:
            fields = [file, name, change.operator, shorten(original), shorten(alternative.replacement)]
            ordinal = counts.get(tuple(fields), 0)
            counts[tuple(fields)] = ordinal + 1
            site = {"id": ",".join(escape(f) for f in fields + [str(ordinal)]), **site, "ordinal": ordinal}
        site.update({"line": change.start[0], "column": change.start[1], "definition_lines": lines,
                     "pinned": alternative.pinned, "operator_set": ops.VERSION})
        if alternative.skipped is not None:
            site["skipped"] = alternative.skipped
        sites.append(site)
    return sites


def deduplicated(source, changes):
    """The indices of the changes to keep, where two make the same mutant:
    the pinned one, then the one whose operator comes first in
    operators.DEDUPLICATION. A skipped site that a kept site's mutant
    already makes is no site at all. A skipped BODY site, which has no
    replacement, is always kept."""
    preference = {o: i for i, o in enumerate(ops.DEDUPLICATION)}

    def effect_of(index):
        change = changes[index]
        if change.same_as is not None:
            start, end = source.offset(*change.same_as[0]), source.offset(*change.same_as[1])
            return effect(source, start, end, change.same_as[2])
        start, end = source.offset(*change.start), source.offset(*change.end)
        return effect(source, start, end, change.alternative.replacement)

    def ranked(indices):
        return sorted(indices, key=lambda i: (not changes[i].alternative.pinned,
                                              preference[changes[i].operator], i))

    mutants, skipped, keep = {}, {}, set()
    for index in ranked(i for i, c in enumerate(changes) if c.alternative.skipped is None):
        mutants.setdefault(effect_of(index), index)
    for index in ranked(i for i, c in enumerate(changes) if c.alternative.skipped is not None):
        if changes[index].alternative.skipped in (ops.NO_DEFAULT, ops.FFI):
            keep.add(index)
        elif effect_of(index) not in mutants:
            skipped.setdefault(effect_of(index), index)
    return keep | set(mutants.values()) | set(skipped.values())


def main():
    parser = argparse.ArgumentParser(description="Print the mutation sites of MoonBit source, one per line.")
    parser.add_argument("--root", default=".", help="the directory the paths are relative to")
    parser.add_argument("--target", default="wasm-gc", help="the backend whose conditional compilation applies")
    parser.add_argument("--set", default="pinned", choices=("pinned", "full"),
                        help="the pinned set (the default) or the full set")
    parser.add_argument("--moonc", default="moonc", help="the compiler")
    parser.add_argument("--jobs", type=int, default=4, help="how many files the compiler parses at once")
    parser.add_argument("paths", nargs="+")
    args = parser.parse_args()
    root = Path(args.root)
    try:
        files = source_files(root, args.paths)
        texts = {}
        for path in files:
            text = (root / path).read_text(encoding="utf-8")
            if not is_generated(text):
                texts[path] = text
        with tempfile.TemporaryDirectory(prefix="smock-sites-") as tmp:
            work = Path(tmp)
            with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
                trees = list(pool.map(
                    lambda p: dump(args.moonc, args.target, work, p[0], p[1], texts[p[1]]),
                    enumerate(texts)))
        for path, tree in zip(texts, trees):
            for site in file_sites(SourceFile(path, texts[path]), tree):
                if args.set == "full" or site["pinned"]:
                    print(json.dumps(site, ensure_ascii=False))
    except FinderError as error:
        print(f"sites: {error}", file=sys.stderr)
        sys.exit(1)
    except FileNotFoundError as error:
        print(f"sites: {error}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
