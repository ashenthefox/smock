#!/usr/bin/env python3
"""Finds the sites of the mutation runner in MoonBit source, and prints one
site per line, as JSON. A site is one change that one operator can make at
one place (CONTRIBUTING.md, "Mutation runner").

usage: python3 scripts/mutation/sites.py [--root <dir>] [--target <backend>] <path>...

Each <path> is a package's directory, whose .mbt files are read, or one
.mbt file, relative to <root> (the current directory unless it is given).
Test files (*_test.mbt, *_wbtest.mbt), test blocks, and generated files
have no sites. A generated file is one whose first line is
"// Generated by <what>. Do not edit.": the Unicode data table, the build
information and the test certificates are.

The operators are those of operator set v1 that the runner has so far:

  ROR   a comparison, with its boundary alternative: < and <= swap, and
        > and >= swap
  BOOL  true and false swap
  NOT   a prefix ! removed

Each line is a JSON object with:

  id                the mutant's id: the six fields below, joined by ","
                    (a "\\" escapes a "," or a "\\" in a field, and "\\n",
                    "\\r" and "\\t" stand for those characters)
  file              the file, relative to <root>, with "/"
  definition        the top-level definition that holds the site: "f",
                    "Type::f", "impl Trait for Type with f", a let or a
                    const's name, a type's or a trait's name, main or init
  operator          ROR, BOOL or NOT
  original          the text the site replaces
  replacement       the text that replaces it ("" for NOT)
  ordinal           how many sites with the same file, definition,
                    operator, original and replacement come before it in
                    the file, from 0
  line, column      where the original text starts, from 1; a column counts
                    characters (Unicode code points)
  definition_lines  the first and the last line of the definition

The lines are sorted by file, then by position. The ids stay the same as
long as a definition's sites of the same kind keep their order.

The parser is the pinned compiler's own: `moonc compile -dsource -show-loc`
writes the parse tree of a file, with the position of every node, beside
it. The file is copied into a temporary directory first, so the tree is
written there. The compiler then fails to type the file, which it reads
without its package; only a parse error fails this script. Every site's
original text is checked against the source at the position the tree
gives, so a tree that changes shape fails the script instead of giving a
wrong site. --target is the backend whose conditional compilation the
compiler applies (wasm-gc unless it is given). The runner,
scripts/mutation/run.py, reads only these lines, so another parser can
replace this one without a change to the runner.
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

GENERATED = re.compile(r"^// Generated by .+\. Do not edit\.$")
LOC = re.compile(r"^(\d+):(\d+)-(\d+):(\d+)$")
ROR = {"<": "<=", "<=": "<", ">": ">=", ">=": ">"}
BOOL = {"true": "false", "false": "true"}
# The beginnings of a literal's text, whose value the tree prints as a bare
# word: the string "true", and the bytes b"true", are printed as true.
LITERAL_STARTS = ('"', "'", 'b"', "b'", "#|", "$|")


class FinderError(Exception):
    """What stops the finder: a file that does not parse, or a tree it
    cannot read."""


def is_test_file(path):
    """Whether moon reads the file as tests only."""
    return path.name.endswith(("_test.mbt", "_wbtest.mbt"))


def is_generated(text):
    """Whether the file's first line says that a generator wrote it."""
    return GENERATED.match(text.split("\n", 1)[0]) is not None


def source_files(root, paths):
    """The .mbt files that the paths name, relative to root, without tests
    and generated files, sorted."""
    files = set()
    for given in paths:
        path = (root / given).resolve()
        if path.is_dir():
            candidates = sorted(path.glob("*.mbt"))
        elif path.is_file():
            candidates = [path]
        else:
            raise FinderError(f"{given} is neither a package's directory nor a file")
        for file in candidates:
            if file.suffix == ".mbt" and not is_test_file(file):
                files.add(file.relative_to(root.resolve()))
    return sorted(files, key=lambda p: p.as_posix())


def parse_tree(text):
    """The compiler's dump, an S-expression, as nested lists of strings."""
    stack = [[]]
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c in " \t\r\n":
            i += 1
        elif c == "(":
            stack.append([])
            i += 1
        elif c == ")":
            if len(stack) == 1:
                raise FinderError("the parse tree has an unmatched )")
            node = stack.pop()
            stack[-1].append(node)
            i += 1
        elif c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            if j >= n:
                raise FinderError("the parse tree has an unterminated string")
            stack[-1].append(text[i : j + 1])
            i = j + 1
        else:
            j = i
            while j < n and text[j] not in ' \t\r\n()"':
                j += 1
            stack[-1].append(text[i:j])
            i = j
    if len(stack) != 1 or len(stack[0]) != 1 or not isinstance(stack[0][0], list):
        raise FinderError("the parse tree is not one list")
    return stack[0][0]


def child(node, head):
    """The first list among node's elements that starts with head, or None."""
    for element in node:
        if isinstance(element, list) and element and element[0] == head:
            return element
    return None


def walk(node):
    """Every list in node, node included, depth first, without recursion."""
    todo = [node]
    while todo:
        current = todo.pop()
        yield current
        todo.extend(reversed([e for e in current if isinstance(e, list)]))


def first_binder(node):
    """The first name that node binds, or None."""
    for current in walk(node):
        if len(current) == 2 and current[0] == "binder_name" and isinstance(current[1], str):
            return current[1]
    return None


class SourceFile:
    """A file's text, and where each of its lines starts."""

    def __init__(self, path, text):
        self.path = path
        self.text = text
        self.starts = [0]
        for line in text.split("\n"):
            self.starts.append(self.starts[-1] + len(line) + 1)

    def offset(self, line, column):
        """The offset of a line and a column, both from 1."""
        if not 1 <= line < len(self.starts):
            raise FinderError(f"{self.path}: the parse tree names line {line}, which the file does not have")
        return self.starts[line - 1] + column - 1

    def between(self, start, end):
        """The text from one (line, column) to another, the end excluded."""
        return self.text[self.offset(*start) : self.offset(*end)]


class Item:
    """One top-level definition of the parse tree, with its base line: the
    tree gives each position inside it as a line relative to that base."""

    def __init__(self, source, base, node):
        self.source = source
        self.node = node
        match = re.match(r"^(\d+):(\d+)$", base)
        if not match or match.group(2) != "1":
            raise FinderError(f"{source.path}: unexpected base position {base} in the parse tree")
        self.base = int(match.group(1))

    def loc(self, atom):
        """A location atom as ((line, column), (line, column)) in the file,
        or None when it is not one or the compiler made it up (0:0-0:0)."""
        if not isinstance(atom, str):
            return None
        match = LOC.match(atom)
        if not match:
            return None
        l1, c1, l2, c2 = (int(g) for g in match.groups())
        if (l1, c1, l2, c2) == (0, 0, 0, 0):
            return None
        return (self.base + l1, c1), (self.base + l2, c2)

    def text_of(self, node):
        """The source text of a node that ends with, or holds, its location."""
        for element in [node[-1]] + [e[1] for e in node if isinstance(e, list) and len(e) == 2 and e[0] == "loc_"]:
            span = self.loc(element)
            if span:
                return self.source.between(*span)
        return None

    def is_test(self):
        kind = self.node[0]
        if kind == "Ptop_test":
            return True
        if kind == "Ptop_funcdef" and isinstance(self.node[1], list):
            flag = child(self.node[1], "is_test_")
            return flag is not None and flag[1:] == ["true"]
        return False

    def name(self):
        """The definition's name, as the ids give it."""
        node, kind = self.node, self.node[0]
        if kind == "Ptop_funcdef":
            header = node[1]
            name = child(header, "name")
            method = first_binder(name) if name else None
            owner = child(header, "type_name")
            if owner and owner[1:] and isinstance(owner[1], list) and owner[1]:
                type_name = child(owner[1][0], "name")
                if type_name and method:
                    return f"{type_name[1]}::{method}"
            if method:
                return method
        elif kind == "Ptop_impl":
            # The type is optional, so it comes in a list: empty for a
            # trait's default implementation.
            self_type, trait, method = node[1], node[2], node[3]
            trait_text = self.text_of(trait)
            method_name = first_binder([method])
            type_text = self.text_of(self_type[0]) if self_type else None
            if trait_text and method_name and (type_text or not self_type):
                if type_text:
                    return f"impl {trait_text} for {type_text} with {method_name}"
                return f"impl {trait_text} with {method_name}"
        elif kind == "Ptop_expr":
            return "main" if "true" in node[2:-1] else "init"
        elif kind in ("Ptop_letdef", "Ptop_trait"):
            binder = first_binder(node)
            if binder:
                return binder
        elif kind == "Ptop_typedef":
            tycon = child(node[1], "tycon")
            if tycon:
                return tycon[1]
        binder = first_binder(node)
        return f"{kind} {binder}" if binder else kind

    def lines(self):
        """The first and the last line of the definition."""
        span = self.loc(self.node[-1])
        if span:
            return [span[0][0], span[1][0]]
        found = [self.loc(a) for n in walk(self.node) for a in n if isinstance(a, str)]
        found = [s for s in found if s]
        return [min(s[0][0] for s in found), max(s[1][0] for s in found)]

    def sites(self):
        """Every site in the definition, as (operator, original, replacement, (line, column))."""
        for node in walk(self.node):
            head = node[0] if node and isinstance(node[0], str) else None
            if head == "Pexpr_infix" and isinstance(node[1], list):
                op, span = child(node[1], "var_name"), child(node[1], "loc_")
                if op and span and op[1] in ROR:
                    yield self.checked("ROR", op[1], ROR[op[1]], self.loc(span[1]))
            elif head == "Pexpr_unary" and isinstance(node[1], list):
                op, span = child(node[1], "var_name"), child(node[1], "loc_")
                if op and span and op[1] == "!":
                    yield self.checked("NOT", "!", "", self.loc(span[1]))
            elif head == "Pexpr_constant" and len(node) >= 3 and node[1] in BOOL:
                span = self.loc(node[2])
                if span is None:
                    continue
                text = self.source.between(*span)
                if text.startswith(LITERAL_STARTS):
                    continue
                yield self.checked("BOOL", node[1], BOOL[node[1]], span)

    def checked(self, operator, original, replacement, span):
        if span is None:
            raise FinderError(f"{self.source.path}: a {operator} node of the parse tree has no position")
        start = span[0]
        offset = self.source.offset(*start)
        found = self.source.text[offset : offset + len(original)]
        if found != original:
            raise FinderError(
                f"{self.source.path}:{start[0]}:{start[1]}: the parse tree puts {original!r} here,"
                f" but the source has {found!r}"
            )
        return operator, original, replacement, start


def dump(moonc, target, workdir, index, path, text):
    """The parse tree of one file, which moonc writes beside a copy of it."""
    directory = workdir / str(index)
    directory.mkdir()
    copy = directory / path.name
    copy.write_text(text, encoding="utf-8")
    result = subprocess.run(
        [moonc, "compile", "-dsource", "-show-loc", "-target", target, "-error-format", "json",
         copy.name, "-o", "out.wasm"],
        cwd=directory, capture_output=True, text=True,
    )
    for line in (result.stdout + result.stderr).splitlines():
        try:
            diagnostic = json.loads(line)
        except ValueError:
            continue
        code = str(diagnostic.get("error_code", ""))
        if diagnostic.get("level") == "error" and code.startswith("3") and len(code) == 4:
            raise FinderError(f"{path}: moonc cannot parse it: {diagnostic.get('message')}")
    tree = directory / (copy.name + ".ast")
    if not tree.is_file():
        raise FinderError(f"{path}: moonc wrote no parse tree:\n{result.stdout}{result.stderr}")
    return tree.read_text(encoding="utf-8")


def escape(field):
    """A field of an id, with what would split it escaped."""
    return (field.replace("\\", "\\\\").replace(",", "\\,").replace("\n", "\\n")
            .replace("\r", "\\r").replace("\t", "\\t"))


def file_sites(source, tree_text):
    """The sites of one file, sorted by position, with their ordinals."""
    found = {}
    for entry in parse_tree(tree_text):
        if not (isinstance(entry, list) and len(entry) == 3 and entry[0] == "base_pos"):
            raise FinderError(f"{source.path}: unexpected entry in the parse tree: {str(entry)[:80]}")
        item = Item(source, entry[1], entry[2])
        if item.is_test():
            continue
        name, lines = item.name(), item.lines()
        for operator, original, replacement, start in item.sites():
            found[(start, operator)] = (name, lines, operator, original, replacement, start)
    counts = {}
    sites = []
    for name, lines, operator, original, replacement, start in sorted(found.values(), key=lambda s: s[5]):
        key = (name, operator, original, replacement)
        ordinal = counts.get(key, 0)
        counts[key] = ordinal + 1
        file = source.path.as_posix()
        fields = [file, name, operator, original, replacement, str(ordinal)]
        sites.append({
            "id": ",".join(escape(f) for f in fields),
            "file": file,
            "definition": name,
            "operator": operator,
            "original": original,
            "replacement": replacement,
            "ordinal": ordinal,
            "line": start[0],
            "column": start[1],
            "definition_lines": lines,
        })
    return sites


def main():
    parser = argparse.ArgumentParser(description="Print the mutation sites of MoonBit source, one per line.")
    parser.add_argument("--root", default=".", help="the directory the paths are relative to")
    parser.add_argument("--target", default="wasm-gc", help="the backend whose conditional compilation applies")
    parser.add_argument("--moonc", default="moonc", help="the compiler")
    parser.add_argument("--jobs", type=int, default=4, help="how many files the compiler parses at once")
    parser.add_argument("paths", nargs="+")
    args = parser.parse_args()
    root = Path(args.root)
    try:
        files = source_files(root, args.paths)
        texts = {}
        for path in files:
            text = (root / path).read_text(encoding="utf-8")
            if not is_generated(text):
                texts[path] = text
        with tempfile.TemporaryDirectory(prefix="smock-sites-") as tmp:
            work = Path(tmp)
            with ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
                trees = list(pool.map(
                    lambda p: dump(args.moonc, args.target, work, p[0], p[1], texts[p[1]]),
                    enumerate(texts)))
        for path, tree in zip(texts, trees):
            for site in file_sites(SourceFile(path, texts[path]), tree):
                print(json.dumps(site, ensure_ascii=False))
    except FinderError as error:
        print(f"sites: {error}", file=sys.stderr)
        sys.exit(1)
    except FileNotFoundError as error:
        print(f"sites: {error}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
